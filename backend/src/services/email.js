// Email service — sends via local Postfix (port 25) which relays through AWS SES.
// In dev mode (EMAIL_DISABLED=1 in env) emails are logged instead of sent.

const nodemailer = require('nodemailer');
const fs = require('fs');
const path = require('path');

const FROM = process.env.EMAIL_FROM || 'info@besafe.org.pl';
const FROM_NAME = process.env.EMAIL_FROM_NAME || 'be:Safe';
const APP_URL = process.env.APP_URL || 'https://besafe.org.pl';
const DISABLED = process.env.EMAIL_DISABLED === '1' || process.env.EMAIL_DISABLED === 'true';

// Two modes:
//  1) Local Postfix (AWS EC2): host=localhost port=25 no auth, ignoreTLS.
//  2) Direct SES SMTP (Cloud Run): host=email-smtp.eu-central-1.amazonaws.com
//     port=587 SMTP_USER+SMTP_PASS, STARTTLS required.
let transporter = null;
function getTransporter() {
  if (transporter) return transporter;
  const host = process.env.SMTP_HOST || 'localhost';
  const port = parseInt(process.env.SMTP_PORT || '25', 10);
  const useAuth = !!process.env.SMTP_USER;

  // If we're using auth (SES SMTP), enforce STARTTLS. Otherwise localhost trust.
  transporter = nodemailer.createTransport({
    host,
    port,
    secure: port === 465,           // SES SSL port; 587 uses STARTTLS via requireTLS
    requireTLS: useAuth,
    ignoreTLS: !useAuth,
    auth: useAuth ? {
      user: process.env.SMTP_USER,
      pass: process.env.SMTP_PASS,
    } : undefined,
  });
  return transporter;
}

/**
 * Load HTML template from ../templates/<name>.html and substitute {{placeholders}}.
 * Returns {html, text} pair; text is auto-generated by stripping tags.
 */
function renderTemplate(name, vars = {}) {
  const file = path.join(__dirname, '..', 'templates', `${name}.html`);
  if (!fs.existsSync(file)) {
    throw new Error(`Email template not found: ${name}`);
  }
  let html = fs.readFileSync(file, 'utf8');
  for (const [k, v] of Object.entries(vars)) {
    html = html.replaceAll(`{{${k}}}`, escapeHtml(String(v ?? '')));
    html = html.replaceAll(`{{${k}_RAW}}`, String(v ?? ''));
  }
  const text = html
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\n\s*\n/g, '\n\n')
    .trim();
  return { html, text };
}

function escapeHtml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Send an email. Returns {ok, messageId, error}.
 * Never throws — errors are logged and returned as {ok: false, error}.
 */
async function send({ to, subject, template, vars = {}, replyTo }) {
  if (DISABLED) {
    console.log(`[email:dev] to=${to} subject=${subject} template=${template}`);
    return { ok: true, devMode: true };
  }
  try {
    const { html, text } = renderTemplate(template, { ...vars, APP_URL });
    const info = await getTransporter().sendMail({
      from: `"${FROM_NAME}" <${FROM}>`,
      to,
      subject,
      html,
      text,
      replyTo: replyTo || FROM,
    });
    console.log(`[email] sent to=${to} subject="${subject}" messageId=${info.messageId}`);
    return { ok: true, messageId: info.messageId };
  } catch (e) {
    console.error(`[email] FAILED to=${to} subject="${subject}": ${e.message}`);
    return { ok: false, error: e.message };
  }
}

// ---- High-level helpers ----

async function sendVerificationEmail({ to, username, verifyUrl }) {
  return send({
    to,
    subject: 'Potwierdź swój email w be:Safe',
    template: 'verification',
    vars: { username: username || 'Użytkowniku', verify_url: verifyUrl, VERIFY_URL_RAW: verifyUrl },
  });
}

async function sendPasswordResetEmail({ to, username, resetUrl }) {
  return send({
    to,
    subject: 'Resetowanie hasła w be:Safe',
    template: 'reset-password',
    vars: { username: username || 'Użytkowniku', reset_url: resetUrl, RESET_URL_RAW: resetUrl },
  });
}

async function sendWelcomeEmail({ to, username }) {
  return send({
    to,
    subject: 'Witamy w be:Safe!',
    template: 'welcome',
    vars: { username: username || 'Użytkowniku' },
  });
}

module.exports = {
  send,
  sendVerificationEmail,
  sendPasswordResetEmail,
  sendWelcomeEmail,
};
